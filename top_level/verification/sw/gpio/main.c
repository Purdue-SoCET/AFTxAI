#include "../include/aft_map.h"
int main() {
    REG32(GPIO0_BASE + 0x08) = 0x0000FFFF;
    CHECK_EQ(REG32(GPIO0_BASE + 0x08), 0x0000FFFF);
    REG32(GPIO0_BASE + 0x04) = 0x0000A5A5;
    CHECK_EQ(REG32(GPIO0_BASE + 0x04), 0x0000A5A5);
    REG32(GPIO0_BASE + 0x04) = 0x00005A5A;
    CHECK_EQ(REG32(GPIO0_BASE + 0x04), 0x00005A5A);
    REG32(GPIO0_BASE + 0x18) = 0xFFFF0000;
    CHECK_EQ(REG32(GPIO0_BASE + 0x18), 0xFFFF0000);
    REG32(GPIO0_BASE + 0x24) = 0x00010000;
    CHECK_EQ(REG32(GPIO0_BASE + 0x24), 0x00010000);
    TEST_PASS();
}
